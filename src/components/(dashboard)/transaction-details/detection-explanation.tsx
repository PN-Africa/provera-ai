interface DetectionExplanationProps {
  amount: string;
  indicator: string;
  risk: "High risk" | "Medium risk" | "Low risk";
}

export function DetectionExplanation({
  amount,
  indicator,
  risk,
}: DetectionExplanationProps) {
  const explanations: Record<
    string,
    { title: string; description: string; nextStep: string }
  > = {
    "High amount": {
      title: "High amount",
      description: `${amount} meets or exceeds the demo's configured high-value threshold of NGN 200,000.`,
      nextStep:
        "Compare the transaction with the customer's expected activity and applicable review guidelines.",
    },
    "Repeated customer activity": {
      title: "Repeated customer activity",
      description:
        "The demo detected three or more transactions associated with the same customer in the uploaded dataset.",
      nextStep:
        "Review the transaction sequence and determine whether the frequency is expected.",
    },
    "Transaction frequency": {
      title: "Transaction frequency",
      description:
        "The sample transaction is associated with a frequency indicator. Check the available transaction history for repeated activity.",
      nextStep:
        "Review nearby transactions and verify the activity against available context.",
    },
    "High amount + deviation": {
      title: "High amount and deviation",
      description:
        "The sample data labels this transaction with both a high-amount indicator and an amount-deviation indicator. Historical comparison details have not been verified.",
      nextStep:
        "Review the amount and verify any historical comparison before making a decision.",
    },
    "No indicator triggered": {
      title: "No indicator triggered",
      description:
        "None of the configured demo rules flagged this transaction. This does not guarantee that the transaction is safe.",
      nextStep:
        "Continue with your normal review process if additional checks are required.",
    },
  };

  const explanation = explanations[indicator] ?? {
    title: indicator || "No indicator details",
    description:
      "No specific explanation is available for this indicator in the current demo.",
    nextStep:
      "Review the available transaction information before deciding what to do next.",
  };

  return (
    <div className="rounded-[10px] border border-[#343644] bg-[#202026] p-6">
      <p className="font-sans text-[12px] font-medium uppercase leading-[18px] text-[#B7B9CB]">
        Detection explanation
      </p>

      <h2 className="mt-3 font-manrope text-[28px] font-medium leading-[36px] tracking-[-0.3px] text-[#EDEFFF]">
        {risk === "Low risk"
          ? "No demo indicators triggered"
          : "Why this needs a closer look"}
      </h2>

      <div className="mt-5">
        <h3 className="font-manrope text-[20px] font-medium leading-[28px] text-[#EDEFFF]">
          {explanation.title}
        </h3>

        <p className="mt-3 font-sans text-[16px] leading-[24px] text-[#B7B9CB]">
          {explanation.description}
        </p>
      </div>

      <div className="mt-5 rounded-[7px] border border-[#343644] bg-[#202026] px-4 py-4">
        <p className="font-sans text-[12px] font-medium uppercase leading-[18px] text-[#B7B9CB]">
          Suggested next step
        </p>
        <p className="mt-2 font-sans text-[14px] leading-[22px] text-[#EDEFFF]">
          {explanation.nextStep}
        </p>
      </div>

      <p className="mt-5 font-sans text-[14px] leading-[20px] text-[#B7B9CB]">
        These indicators are generated by demo rules and are not proof of fraud.
        Review the available evidence before making a decision.
      </p>
    </div>
  );
}
